const fs=require('fs'),ts=require('typescript'),assert=require('assert/strict');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,f);
const {parseTraffic,trafficQuery}=require('../lib/shopify-traffic-data.ts');
const names=['day','utm_source','utm_medium','utm_campaign','utm_content','sessions','pageviews'];
const columns=names.map(name=>({name})),id='12345678-1234-1234-1234-123456789012';
const row=['2026-11-01','tiktok','organic_social','meedoo_video',id,'2','5'];
const parse=rows=>parseTraffic({parseErrors:[],tableData:{columns,rows}},'2026-11-01','2026-11-03');
assert.equal(parse([row])[0].videoId,id);
assert.equal(parse([Object.fromEntries(names.map((n,i)=>[n,row[i]]))])[0].sessions,2);
assert.equal(parse([row,row])[0].sessions,4);
assert.equal(parse([['2026-11-01','unknown','email','campaign','private text',0,0]])[0].videoId,null);
assert.equal(JSON.stringify(parse([['2026-11-01','unknown','email','campaign','private text',0,0]])).includes('private text'),false);
assert.throws(()=>parse([[...row.slice(0,5),null,5]]));
assert.throws(()=>parse([[...row.slice(0,5),-1,5]]));
assert.throws(()=>parseTraffic({parseErrors:['denied'],tableData:{columns,rows:[]}},'2026-11-01','2026-11-03'));
assert.throws(()=>parse(Array(10000).fill(row)));
assert.throws(()=>trafficQuery("2026-11-01 OR true",'2026-11-03'));
assert.match(trafficQuery('2026-11-01','2026-11-03'),/TIMEZONE 'Asia\/Singapore'/);
assert.match(trafficQuery('2026-11-01','2026-11-03'),/human_or_bot_session = 'human'/);
